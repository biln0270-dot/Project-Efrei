    <h1>COMMENT SONT LES COURS À EFREI ?</h1>
    <p>
      À l'EFREI, les cours sont très orientés pratique et projets. Les étudiants suivent des cours magistraux pour les bases théoriques (mathématiques, algorithmique, réseaux), complétés par beaucoup de TD et TP en petits groupes.
    </p>
    <p>
      Le travail se fait souvent en équipe comme en entreprise : développement d'applications, bases de données, gestion d'infrastructures. L'école met aussi l'accent sur les projets concrets pour vous préparer au monde professionnel.
    </p>
